pub fn dispatch_algorithm(id: usize, data: &PreparedData, cfg: &RunConfig) -> AlgorithmOutput {
    match id {
        1..=30 => cat1_centroid::run(id, data, cfg),
        31..=55 => cat2_density::run(id, data, cfg),
        56..=80 => cat3_hierarchical::run(id, data, cfg),
        81..=102 => cat4_distribution::run(id, data, cfg),
        103..=132 => cat5_graph::run(id, data, cfg),
        133..=150 => cat6_grid_subspace::run(id, data, cfg),
        151..=175 => cat7_fuzzy_domain::run(id, data, cfg),
        176..=200 => cat8_neural_stream::run(id, data, cfg),
        _ => AlgorithmOutput::new(vec![-1; data.n_samples], "", "Ukjent algoritme-ID"),
    }
}
